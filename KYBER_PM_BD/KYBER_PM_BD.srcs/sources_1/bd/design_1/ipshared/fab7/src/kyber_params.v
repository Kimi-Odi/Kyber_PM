// =============================================================================
// kyber_params.v
// -----------------------------------------------------------------------------
// 全域常數定義檔。所有模組透過 `include "kyber_params.v" 引用。
//
// 用 `define 而不是 module 外的 parameter,因為 Vivado 預設 Verilog-95/2K
// 模式不允許 root-scope 的 parameter 宣告(必須在 module 內或要切到
// SystemVerilog)。`define 是 preprocessor 巨集,任何模式都吃。
// =============================================================================
`ifndef KYBER_PARAMS_V
`define KYBER_PARAMS_V

// -----------------------------------------------------------------------------
// Kyber 演算法常數
// -----------------------------------------------------------------------------
`define KYBER_Q     3329      // 模數 q,12-bit 質數
                              // 3329 = 13 * 256 + 1,讓我們可以用 low-complexity
                              // Barrett (0 DSP) 做模約化

`define KYBER_N     256       // 多項式長度 n = 256

`define KYBER_LOGN  8         // log2(N) = 8
                              // (Kyber 的 NTT 是 incomplete NTT,只跑 7 層)

// -----------------------------------------------------------------------------
// 硬體資料寬度
// -----------------------------------------------------------------------------
`define DATA_WIDTH      16    // 係數寬度。q 只要 12-bit 就夠,用 16-bit 對齊
                              // DSP/byte 邊界,合成器較好處理。高 4 位永遠 0。

`define ADDR_WIDTH      8     // 256 個係數的位址寬度 (log2(256) = 8)

`define TW_ADDR_WIDTH   7     // Twiddle ROM 位址寬度 (128 entries, log2(128) = 7)

`endif